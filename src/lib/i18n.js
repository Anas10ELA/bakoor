export function t(language, key, values = {}) {
  const template = strings[language]?.[key] || strings.ar[key] || key;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template
  );
}

export function localizeTitle(title, language) {
  return language === "en" ? knownTitles[title] || title : title;
}

export function localizeMinimumVersion(value, language) {
  return language === "en" ? knownMinimumVersions[value] || value : value;
}
